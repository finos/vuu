#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import {
  buildComponentModel,
  componentReferences,
} from "./build-component-model.ts";
import type { ComponentModelConfig } from "./component-model-types.ts";

const { values } = parseArgs({
  options: {
    config: { type: "string", short: "c" },
    module: { type: "string", short: "m" },
  },
});

if (!values.config || !values.module) {
  console.error(
    "usage: component-model --config <components.json> --module <components.js>",
  );
  process.exit(1);
}

const configFile = path.resolve(values.config);
const config = JSON.parse(
  fs.readFileSync(configFile, "utf8"),
) as ComponentModelConfig;
const model = buildComponentModel({
  config,
  configDir: path.dirname(configFile),
});

fs.mkdirSync(path.dirname(values.module), { recursive: true });
fs.writeFileSync(
  values.module,
  [
    "// generated by @vuu-ui/vuu-theme-model - do not edit",
    `export const model = JSON.parse(${JSON.stringify(JSON.stringify(model))});`,
    "",
  ].join("\n"),
);

const summary = model.libraries
  .flatMap((library) =>
    library.components.map(
      (c) =>
        `${library.label} ${c.label} (${c.declarations.length} declarations, ${componentReferences(c).length} variables)`,
    ),
  )
  .join(", ");
console.log(`[component-model] ${summary} => ${values.module}`);
