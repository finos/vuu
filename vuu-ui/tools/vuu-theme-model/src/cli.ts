#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { buildThemeModel } from "./build-theme-model.ts";
import { buildThemeStylesheet } from "./build-theme-stylesheet.ts";
import { summariseThemeModel } from "./summarise-theme-model.ts";
import { buildTokenSearchIndex } from "./token-search-index.ts";

const { values } = parseArgs({
  options: {
    entry: { type: "string", short: "e" },
    out: { type: "string", short: "o" },
    module: { type: "string", short: "m" },
    name: { type: "string", short: "n" },
    summary: { type: "string", short: "s" },
    search: { type: "string" },
    fallback: { type: "string", short: "f", multiple: true },
    pretty: { type: "boolean", short: "p", default: false },
    verbose: { type: "boolean", short: "v", default: false },
  },
});

if (!values.entry) {
  console.error(
    "usage: vuu-theme-model --entry <theme-next.css> [--fallback <theme.css>] [--out model.json] [--module theme.js] [--summary summary.js] [--search search.js] [--name theme-name] [--pretty] [--verbose]",
  );
  process.exit(1);
}

const start = performance.now();
const model = buildThemeModel({
  entry: values.entry,
  fallback: values.fallback,
  name: values.name,
});
const elapsed = Math.round(performance.now() - start);

const write = (file: string, content: string) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
};

const json = `${JSON.stringify(model, null, values.pretty ? 2 : undefined)}\n`;
if (values.out) {
  write(values.out, json);
} else if (!values.module) {
  process.stdout.write(json);
}

if (values.module) {
  // An ES module exporting the model plus a flattened stylesheet of the theme,
  // consumable by any bundler. The model is embedded as a JSON string, which is
  // cheaper to parse than an equivalent object literal.
  const stylesheet = buildThemeStylesheet({
    entry: values.entry,
    fallback: values.fallback,
  });
  write(
    values.module,
    [
      "// generated by @vuu-ui/vuu-theme-model - do not edit",
      `export const model = JSON.parse(${JSON.stringify(JSON.stringify(model))});`,
      `export const stylesheet = ${JSON.stringify(stylesheet)};`,
      "",
    ].join("\n"),
  );
}

if (values.summary) {
  // A tiny companion module with headline figures, cheap to import eagerly
  write(
    values.summary,
    [
      "// generated by @vuu-ui/vuu-theme-model - do not edit",
      `export const summary = ${JSON.stringify(summariseThemeModel(model))};`,
      "",
    ].join("\n"),
  );
}

if (values.search) {
  // Tokens with resolved light/dark values, for search (e.g. a command palette)
  write(
    values.search,
    [
      "// generated by @vuu-ui/vuu-theme-model - do not edit",
      `export const tokens = JSON.parse(${JSON.stringify(JSON.stringify(buildTokenSearchIndex(model)))});`,
      "",
    ].join("\n"),
  );
}

const outFile = values.module ?? values.out;
const log = outFile ? console.log : console.error;
const tokens = Object.values(model.tokens);
const countByTier = (tier: string) =>
  tokens.filter((t) => t.tier === tier && t.layer !== "legacy").length;
const legacyCount = tokens.filter((t) => t.layer === "legacy").length;
log(
  `[vuu-theme-model] ${model.name}: ${tokens.length} tokens (foundations ${countByTier("foundations")}, palette ${countByTier("palette")}, characteristics ${countByTier("characteristics")}, legacy fallback ${legacyCount}), ${model.scopes.length} scopes, axes [${model.axes.map((a) => `${a.name}: ${a.values.join("|")}`).join(", ")}], ${model.diagnostics.length} diagnostics in ${elapsed}ms${[
    values.out,
    values.module,
    values.summary,
  ]
    .filter(Boolean)
    .map((f) => ` => ${f}`)
    .join("")}`,
);
if (values.verbose) {
  for (const d of model.diagnostics) {
    log(`  ${d.type}: ${d.message}`);
  }
}
