import { useEffect, useId, useRef, useState } from "react";
import { useChromeModeContext } from "./showcase-main/chrome/ChromeModeContext";

export interface MermaidProps {
  /** Mermaid diagram source */
  chart: string;
}

/** Mermaid theme variables, from the showcase chrome tokens */
const chromeThemeVariables = (el: HTMLElement) => {
  const style = getComputedStyle(el);
  const token = (name: string) => style.getPropertyValue(`--sc-${name}`).trim();
  return {
    background: token("surface"),
    clusterBkg: token("surface-2"),
    clusterBorder: token("border-strong"),
    edgeLabelBackground: token("surface"),
    fontFamily: token("font"),
    fontSize: "13px",
    lineColor: token("text-3"),
    mainBkg: token("surface-2"),
    nodeBorder: token("border-strong"),
    noteBkgColor: token("surface-3"),
    noteTextColor: token("text"),
    primaryBorderColor: token("accent"),
    primaryColor: token("surface-2"),
    primaryTextColor: token("text"),
    secondaryColor: token("surface-3"),
    tertiaryColor: token("surface"),
    textColor: token("text-2"),
    titleColor: token("text"),
  };
};

/**
 * Renders a Mermaid diagram in an MDX document. Fenced code blocks with the
 * language "mermaid" are converted to this component at build time (see
 * scripts/remark-mermaid.ts). Mermaid is loaded on demand, so pages without
 * diagrams don't pay for it. Diagrams are part of the document, so they are
 * styled by the showcase chrome, never by the preview theme.
 */
export const Mermaid = ({ chart }: MermaidProps) => {
  const { chromeMode } = useChromeModeContext();
  const id = `mermaid-${useId().replace(/[^\w-]/g, "")}`;
  const ref = useRef<HTMLDivElement>(null);
  const [svg, setSvg] = useState<string>();
  const [error, setError] = useState<string>();

  useEffect(() => {
    let cancelled = false;
    import("mermaid")
      .then(async ({ default: mermaid }) => {
        if (cancelled || !ref.current) return;
        mermaid.initialize({
          darkMode: chromeMode === "dark",
          startOnLoad: false,
          theme: "base",
          themeVariables: chromeThemeVariables(ref.current),
        });
        const { svg } = await mermaid.render(`${id}-${chromeMode}`, chart);
        if (!cancelled) {
          setSvg(svg);
          setError(undefined);
        }
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : String(err));
        }
      });
    return () => {
      cancelled = true;
    };
  }, [chart, chromeMode, id]);

  if (error) {
    return (
      <pre className="ShowcaseMermaid ShowcaseMermaid-error">
        {`Mermaid diagram could not be rendered: ${error}\n\n${chart}`}
      </pre>
    );
  }

  return (
    <div
      className="ShowcaseMermaid"
      // biome-ignore lint/security/noDangerouslySetInnerHtml: svg generated by mermaid from document source
      dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
      ref={ref}
    />
  );
};
