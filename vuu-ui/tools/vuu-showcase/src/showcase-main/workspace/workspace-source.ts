import type { Workspace, WorkspacePanel } from "./workspace-model";

/** Details of the example rendered in a panel, from the tree source */
export interface ExampleSourceInfo {
  componentName: string;
  /** source file, relative to the examples root, e.g ./Table/Table.examples.tsx */
  path: string;
}

export type ExampleSourceResolver = (
  route: string,
) => ExampleSourceInfo | undefined;

const toPascalCase = (value: string) =>
  value
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("")
    .replace(/^(\d)/, "_$1") || "Workspace";

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || "panel";

const importPath = (path: string) =>
  `./${path.replace(/^\.\//, "").replace(/\.tsx?$/, "")}`;

const fallbackComponentName = ({ path }: WorkspacePanel) =>
  toPascalCase(path.split("/").pop() ?? "Example");

const quote = (value: string) => JSON.stringify(value);

/** The component name used for the workspace in generated source */
export const workspaceComponentName = (name: string) => toPascalCase(name);

/**
 * Source for a component that reproduces the layout of a workspace, using
 * GridLayout. Stacked panels are declared with a GridLayoutStackedItem.
 */
export const workspaceLayoutSource = (
  { layout, name, panels }: Pick<Workspace, "layout" | "name" | "panels">,
  resolve: ExampleSourceResolver,
) => {
  const importsByFile = new Map<string, Set<string>>();
  const componentNames = new Map<string, string>();
  for (const panel of panels) {
    const info = resolve(panel.path);
    const componentName = info?.componentName ?? fallbackComponentName(panel);
    componentNames.set(panel.id, componentName);
    if (info) {
      const file = importPath(info.path);
      const names = importsByFile.get(file) ?? new Set<string>();
      names.add(componentName);
      importsByFile.set(file, names);
    }
  }

  const usedIds = new Set<string>();
  const uniqueId = (title: string) => {
    const base = slugify(title);
    let id = base;
    for (let i = 2; usedIds.has(id); i++) {
      id = `${base}-${i}`;
    }
    usedIds.add(id);
    return id;
  };
  const ids = new Map(panels.map(({ id, title }) => [id, uniqueId(title)]));

  const stacks = new Map<string, { active: number; gridArea: string }>();
  const stackIds = new Map<string, string>();
  const stackSizes = new Map<string, number>();
  const items: string[] = [];
  for (const panel of panels) {
    const item = layout.items[panel.id];
    if (!item) continue;
    const componentName = componentNames.get(panel.id);
    const id = quote(ids.get(panel.id) ?? panel.id);
    const title = quote(panel.title);
    if (item.stackId) {
      let stackId = stackIds.get(item.stackId);
      if (stackId === undefined) {
        stackId = `stack-${stackIds.size + 1}`;
        stackIds.set(item.stackId, stackId);
        stacks.set(stackId, { active: 0, gridArea: item.gridArea });
      }
      const index = stackSizes.get(stackId) ?? 0;
      stackSizes.set(stackId, index + 1);
      if (item.contentVisible) {
        stacks.set(stackId, { active: index, gridArea: item.gridArea });
      }
      items.push(
        `    <GridLayoutItem id=${id} stackId=${quote(stackId)} title=${title}>`,
        `      <${componentName} />`,
        `    </GridLayoutItem>`,
      );
    } else {
      items.push(
        `    <GridLayoutItem id=${id} title=${title} header`,
        `      style={{ gridArea: ${quote(item.gridArea)} }}>`,
        `      <${componentName} />`,
        `    </GridLayoutItem>`,
      );
    }
  }
  for (const [stackId, { active, gridArea }] of stacks) {
    items.push(
      `    <GridLayoutStackedItem id=${quote(stackId)} active={${active}}`,
      `      style={{ gridArea: ${quote(gridArea)} }} />`,
    );
  }

  const gridImports = ["GridLayout", "GridLayoutItem"];
  if (stacks.size > 0) {
    gridImports.push("GridLayoutStackedItem");
  }
  const tracks = (sizes: string[]) => `[${sizes.map(quote).join(", ")}]`;

  return [
    `import { ${gridImports.join(", ")} } from "@heswell/grid-layout";`,
    ...Array.from(importsByFile).map(
      ([file, names]) =>
        `import { ${Array.from(names).join(", ")} } from ${quote(file)};`,
    ),
    "",
    `// Workspace ${quote(name)}, generated by Vuu Showcase`,
    `export const ${workspaceComponentName(name)} = () => (`,
    "  <GridLayout",
    `    colsAndRows={{ cols: ${tracks(layout.cols)}, rows: ${tracks(layout.rows)} }}`,
    "    full-page",
    "  >",
    ...items,
    "  </GridLayout>",
    ");",
    "",
  ].join("\n");
};
