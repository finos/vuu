import cx from "clsx";
import {
  type KeyboardEvent,
  type MouseEvent,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
} from "react";
import type {
  AnatomyNode,
  AnatomyRef,
  AnatomyTier,
  ChainStep,
  ComponentAnatomyModel,
} from "./anatomy-types";
import {
  ancestry,
  clipRect,
  displaySelector,
  elementAt,
  groupRefs,
  instanceForNode,
  isColor,
  nodeLabel,
  primaryClass,
  secondaryClasses,
  themeVariableCount,
  visibleSteps,
} from "./anatomy-view-model";

import "./ComponentAnatomy.css";

const classBase = "ShowcaseAnatomy";

/** x-ray outlines: each ancestor level steps out by this much */
const LEVEL_TOP = 18;
const LEVEL_SIDE = 7;
const MARGIN = 12;
/** outline colour by depth, the selected element is always the accent */
const DEPTH_HUES = [
  "#64748b",
  "#0891b2",
  "#7c3aed",
  "#db2777",
  "#ea580c",
  "#16a34a",
  "#ca8a04",
  "#0d9488",
];
const hueFor = (depth: number) => DEPTH_HUES[depth % DEPTH_HUES.length];

const TIER_LABELS: Record<AnatomyTier, string> = {
  hook: "Component hook",
  internal: "Internal",
  characteristics: "Characteristic",
  palette: "Palette",
  foundations: "Foundation",
  other: "Salt (other)",
};
const LEGEND: AnatomyTier[] = [
  "hook",
  "characteristics",
  "palette",
  "foundations",
  "internal",
];

export interface ComponentAnatomyProps {
  /** model generated by `npm run showcase:anatomy` */
  anatomy: ComponentAnatomyModel;
  /** url of the screenshot captured with the model */
  image: string;
  /** class of the element selected initially, e.g `vuuTableCell` */
  initialSelection?: string;
}

const useWidth = () => {
  const ref = useRef<HTMLDivElement>(null);
  const [width, setWidth] = useState(0);
  useLayoutEffect(() => {
    const el = ref.current;
    if (el) {
      setWidth(el.clientWidth);
      const observer = new ResizeObserver(([entry]) =>
        setWidth(entry.contentRect.width),
      );
      observer.observe(el);
      return () => observer.disconnect();
    }
  }, []);
  return [ref, width] as const;
};

/**
 * The anatomy of a component: a captured example with the structure of the
 * selected element drawn as nested outlines (x-ray), the DOM structure and
 * the theme variables each element uses. Styled with showcase chrome tokens
 * only, it never reflects the theme being documented.
 */
export const ComponentAnatomy = ({
  anatomy,
  image,
  initialSelection,
}: ComponentAnatomyProps) => {
  const { component, elements, nodes, size } = anatomy;
  const [selected, setSelected] = useState(() => {
    const node =
      nodes.find(
        (n) => initialSelection && n.classes.includes(initialSelection),
      ) ?? nodes[0];
    return node.instances[0];
  });
  const [hovered, setHovered] = useState<number>();
  const [stageRef, stageWidth] = useWidth();
  const treeRef = useRef<HTMLDivElement>(null);

  const selectedNode = nodes[elements[selected].node];
  const chain = useMemo(
    () => ancestry(elements, selected),
    [elements, selected],
  );
  const maxDepth = useMemo(
    () => Math.max(...nodes.map((n) => n.depth)),
    [nodes],
  );
  const declarations = useMemo(
    () => nodes.reduce((sum, n) => sum + n.refs.length, 0),
    [nodes],
  );

  const [width, height] = size;
  const padX = maxDepth * LEVEL_SIDE + MARGIN;
  const padTop = maxDepth * LEVEL_TOP + MARGIN;
  const padBottom = maxDepth * LEVEL_SIDE + MARGIN + 18;
  const scale =
    stageWidth > 0 ? Math.min(1, (stageWidth - 2 * padX) / width) : 1;

  const toComponent = (e: MouseEvent<HTMLDivElement>) => {
    const box = e.currentTarget.getBoundingClientRect();
    return elementAt(
      anatomy,
      (e.clientX - box.left - padX) / scale,
      (e.clientY - box.top - padTop) / scale,
    );
  };

  const handleStageClick = (e: MouseEvent<HTMLDivElement>) => {
    const hit = toComponent(e);
    if (hit !== undefined) {
      const parent = elements[hit].parent;
      setSelected(e.altKey && parent !== null ? parent : hit);
    }
  };

  const box = (index: number, level = 0) => {
    const [x, y, w, h] = clipRect(elements[index].rect, size);
    return {
      left: padX + x * scale - level * LEVEL_SIDE,
      top: padTop + y * scale - level * LEVEL_TOP,
      width: w * scale + 2 * level * LEVEL_SIDE,
      height: h * scale + level * (LEVEL_TOP + LEVEL_SIDE),
    };
  };

  const selectNode = (nodeId: number) =>
    setSelected(instanceForNode(anatomy, nodeId, selected));

  const handleTreeKeyDown = (e: KeyboardEvent<HTMLDivElement>) => {
    const position = nodes.indexOf(selectedNode);
    const next =
      e.key === "ArrowDown"
        ? position + 1
        : e.key === "ArrowUp"
          ? position - 1
          : e.key === "Home"
            ? 0
            : e.key === "End"
              ? nodes.length - 1
              : e.key === "ArrowLeft" && selectedNode.parent !== null
                ? nodes.findIndex((n) => n.id === selectedNode.parent)
                : -1;
    if (next >= 0 && next < nodes.length) {
      e.preventDefault();
      selectNode(nodes[next].id);
      treeRef.current
        ?.querySelector<HTMLElement>(`[data-node="${nodes[next].id}"]`)
        ?.focus();
    }
  };

  const otherInstances = selectedNode.instances.filter((i) => {
    const [, , w, h] = clipRect(elements[i].rect, size);
    return i !== selected && !elements[i].hidden && w > 0 && h > 0;
  });
  const hoverIndex =
    hovered !== undefined && !chain.includes(hovered) ? hovered : undefined;

  return (
    <section className={classBase} aria-label={`${component} anatomy`}>
      <header className={`${classBase}-header`}>
        <span className={`${classBase}-title`}>{component} anatomy</span>
        <span className={`${classBase}-meta`}>
          {nodes.length} elements · {declarations} declarations
        </span>
        <span className={`${classBase}-capture`}>
          {anatomy.theme} · {anatomy.mode} · {anatomy.density} density
        </span>
      </header>

      <div
        aria-hidden
        className={`${classBase}-stage`}
        onClick={handleStageClick}
        onMouseLeave={() => setHovered(undefined)}
        onMouseMove={(e) => setHovered(toComponent(e))}
        ref={stageRef}
        style={{ height: padTop + height * scale + padBottom }}
        title="Click to select, Alt+click selects the parent"
      >
        <img
          alt=""
          className={`${classBase}-shot`}
          draggable={false}
          src={image}
          style={{
            left: padX,
            top: padTop,
            width: width * scale,
            height: height * scale,
          }}
        />
        {otherInstances.map((i) => (
          <div className={`${classBase}-instance`} key={i} style={box(i)} />
        ))}
        {hoverIndex !== undefined ? (
          <div className={`${classBase}-hover`} style={box(hoverIndex)} />
        ) : null}
        {chain.map((index, k) => {
          const node = nodes[elements[index].node];
          const level = chain.length - 1 - k;
          const isSelected = index === selected;
          const b = box(index, level);
          return (
            <div
              className={cx(`${classBase}-xray`, {
                [`${classBase}-xray-selected`]: isSelected,
              })}
              key={index}
              style={{
                ...b,
                ["--anatomy-hue" as string]: isSelected
                  ? "var(--sc-accent)"
                  : hueFor(node.depth),
              }}
            >
              <span
                className={cx(`${classBase}-tab`, {
                  [`${classBase}-tab-below`]: isSelected && b.height < 30,
                })}
                onClick={(e) => {
                  e.stopPropagation();
                  setSelected(index);
                }}
              >
                {nodeLabel(node, component)}
              </span>
            </div>
          );
        })}
      </div>

      <div className={`${classBase}-split`}>
        <div
          aria-label="DOM structure"
          className={`${classBase}-tree`}
          onKeyDown={handleTreeKeyDown}
          ref={treeRef}
          role="tree"
        >
          {nodes.map((node) => (
            <TreeItem
              component={component}
              isInChain={chain.some((i) => elements[i].node === node.id)}
              isSelected={node === selectedNode}
              key={node.id}
              node={node}
              onHover={setHovered}
              onSelect={selectNode}
            />
          ))}
        </div>
        <VariablesPanel
          component={component}
          node={selectedNode}
          position={selectedNode.instances.indexOf(selected)}
        />
      </div>

      <footer className={`${classBase}-legend`}>
        {LEGEND.map((tier) => (
          <span key={tier}>
            <span className={`${classBase}-dot`} data-tier={tier} />
            {TIER_LABELS[tier]}
          </span>
        ))}
        <span>
          <span className={`${classBase}-dot ${classBase}-dot-unset`} />
          Not set
        </span>
      </footer>
    </section>
  );
};

interface TreeItemProps {
  component: string;
  isInChain: boolean;
  isSelected: boolean;
  node: AnatomyNode;
  onHover: (index?: number) => void;
  onSelect: (nodeId: number) => void;
}

const TreeItem = ({
  component,
  isInChain,
  isSelected,
  node,
  onHover,
  onSelect,
}: TreeItemProps) => {
  const variables = themeVariableCount(node);
  const extra = secondaryClasses(node, component);
  return (
    <div
      aria-level={node.depth + 1}
      aria-selected={isSelected}
      className={cx(`${classBase}-treeItem`, {
        [`${classBase}-treeItem-chain`]: isInChain,
      })}
      data-node={node.id}
      onClick={() => onSelect(node.id)}
      onMouseEnter={() => onHover(node.instances[0])}
      onMouseLeave={() => onHover(undefined)}
      role="treeitem"
      style={{ paddingLeft: 8 + node.depth * 12 }}
      tabIndex={isSelected ? 0 : -1}
    >
      <span
        className={`${classBase}-treeHue`}
        style={{ background: hueFor(node.depth) }}
      />
      <span className={`${classBase}-treeLabel`}>
        <span className={`${classBase}-tag`}>{node.tag}</span>
        {primaryClass(node, component) ? (
          <span>.{primaryClass(node, component)}</span>
        ) : null}
        {node.component ? (
          <span className={`${classBase}-nested`}>{node.component}</span>
        ) : extra.length ? (
          <span className={`${classBase}-extra`}>.{extra.join(".")}</span>
        ) : null}
        {node.variantClasses.length ? (
          <span className={`${classBase}-variant`} title="on some instances">
            {" "}
            .{node.variantClasses.join(" | .")}
          </span>
        ) : null}
      </span>
      {node.total > 1 ? (
        <span
          className={`${classBase}-count`}
          title={`${node.count} per parent, ${node.total} in total`}
        >
          ×{node.total}
        </span>
      ) : null}
      {variables ? (
        <span
          className={`${classBase}-varCount`}
          title={`${variables} theme variables`}
        >
          {variables}
        </span>
      ) : null}
    </div>
  );
};

interface VariablesPanelProps {
  component: string;
  node: AnatomyNode;
  position: number;
}

const VariablesPanel = ({ component, node, position }: VariablesPanelProps) => {
  const groups = useMemo(() => groupRefs(node.refs), [node]);
  return (
    <div className={`${classBase}-vars`} aria-live="polite">
      <div className={`${classBase}-varsHeader`}>
        <span className={`${classBase}-varsTitle`}>
          {nodeLabel(node, component)}
        </span>
        {node.total > 1 ? (
          <span className={`${classBase}-meta`}>
            {position + 1} of {node.total}
          </span>
        ) : null}
        {node.role ? (
          <span className={`${classBase}-meta`}>role={node.role}</span>
        ) : null}
      </div>
      {node.component ? (
        <p className={`${classBase}-note`}>
          A nested {node.component}, only the styles {component} applies to it
          are shown.
        </p>
      ) : null}
      {groups.length === 0 ? (
        <p className={`${classBase}-note`}>
          No theme variables or custom properties are used by this element.
        </p>
      ) : (
        groups.map((group) => (
          <div className={`${classBase}-group`} key={group.title}>
            <div className={`${classBase}-groupTitle`}>{group.title}</div>
            {group.refs.map((ref, i) => (
              <RefRow key={i} node={node} reference={ref} />
            ))}
          </div>
        ))
      )}
    </div>
  );
};

const RefRow = ({
  node,
  reference: ref,
}: {
  node: AnatomyNode;
  reference: AnatomyRef;
}) => {
  const steps = visibleSteps(ref.chain);
  return (
    <div
      className={cx(`${classBase}-ref`, {
        [`${classBase}-ref-overridden`]: ref.overridden,
      })}
      title={`${ref.property}: ${ref.declared.replace(/\s+/g, " ")}\n${ref.selector}`}
    >
      <div className={`${classBase}-refHead`}>
        <span className={`${classBase}-property`}>{ref.property}</span>
        {ref.overridden ? (
          <span className={`${classBase}-flag`}>overridden</span>
        ) : null}
        {ref.instances ? (
          <span className={`${classBase}-flag`}>
            {ref.instances} of {node.total}
          </span>
        ) : null}
        <span className={`${classBase}-value`}>
          {isColor(ref.value) ? (
            <span
              className={`${classBase}-swatch`}
              style={{ background: ref.value }}
            />
          ) : null}
          {ref.value ?? "—"}
        </span>
      </div>
      {ref.instances || ref.states || ref.pseudoElement ? (
        <div className={`${classBase}-selector`}>
          {displaySelector(ref.selector)}
        </div>
      ) : null}
      <div className={`${classBase}-chain`}>
        {steps.map((step, i) => (
          <Step key={i} step={step} />
        ))}
      </div>
    </div>
  );
};

const Step = ({ step }: { step: ChainStep }) =>
  step.kind === "literal" ? (
    <span className={`${classBase}-step ${classBase}-literal`}>
      {step.value.replace(/\s+/g, " ")}
    </span>
  ) : (
    <span
      className={cx(`${classBase}-step`, {
        [`${classBase}-step-unset`]: !step.set,
      })}
      data-tier={step.tier}
      title={
        step.set
          ? `${TIER_LABELS[step.tier]}, set by ${step.selector ?? "inline style"}${step.value !== undefined ? `\n${step.value}` : ""}`
          : `${TIER_LABELS[step.tier]}, not set`
      }
    >
      <span className={`${classBase}-dot`} data-tier={step.tier} />
      {step.name}
    </span>
  );
