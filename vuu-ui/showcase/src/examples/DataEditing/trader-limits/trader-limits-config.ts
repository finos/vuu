/** The limitDefinitions columns the page subscribes to. */
export const limitColumnNames = limitColumns
  .map(({ name }) => name)
  .filter((name) =>
    limitsSchemas.limitDefinitions.columns.some((col) => col.name === name),
  );

/** Columns of the edit-limitDefinitions blueprint not shown in Edit mode. */
const NOT_EDITED = new Set(["effective_from", "effective_to", "owner"]);

/**
 * The edit session shows the columns a user enters, as defined by the
 * edit-limitDefinitions blueprint, other than the effective dates and owner.
 * vuuMsg reports a limit that could not be saved, editChange describes the
 * change saving each limit will make. limit_key, generated by the server, is
 * the row key, so it is not shown in Edit mode.
 */
export const limitsSessionConfig: SessionDataSourceOverrides = {
  columns: [
    ...LIMIT_DEFINITION_COLUMNS.filter((name) => !NOT_EDITED.has(name)),
    "vuuMsg",
    "editChange",
  ],
};

const editLimitColumns = limitColumns.filter(({ name }) =>
  limitsSessionConfig.columns?.includes(name),
);

/**
 * The columns each mode's table has. The column picker offers only these,
 * so View mode never offers editChange, nor Edit mode a column the edit
 * session does not have.
 */
export const limitColumnsByMode: Record<
  EditableTableMode,
  readonly ColumnDescriptor[]
> = {
  create: editLimitColumns,
  edit: editLimitColumns,
  view: limitColumns.filter(({ name }) => limitColumnNames.includes(name)),
};

/**
 * For a release that supports one metric, the values every new limit is
 * given: the metric, and its period when the metric allows only one.
 */
export const getFixedLimitValues = (
  fixedMetric?: string,
): Record<string, string> | undefined => {
  if (fixedMetric === undefined) {
    return undefined;
  }
  const periods = LIMIT_METRICS[fixedMetric]?.periods ?? [];
  return periods.length === 1
    ? { metric: fixedMetric, period: periods[0] }
    : { metric: fixedMetric };
};

/**
 * The columns with a fixed value stay, showing the value every new limit is
 * given, but cannot be entered.
 */
export const withFixedValues = (
  columns: readonly ColumnDescriptor[],
  fixedValues?: Record<string, string>,
) =>
  fixedValues === undefined
    ? columns
    : columns.map((column) =>
        column.name in fixedValues ? { ...column, editable: false } : column,
      );

/** Available in the column picker, but not shown at first. */
